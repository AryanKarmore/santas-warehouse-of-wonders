from typing import List, Tuple, Optional, Dict, Set, Any
from .grid import WarehouseGrid, SearchNode


@dataclass
class SearchResult:
    """Encapsulates the outcome and performance metrics of a search algorithm."""
    algorithm_name: str
    goal_reached: bool
    path: List[Tuple[int, int]]
    actions: List[str]
    path_length: int              # Number of steps/moves
    total_cost: float             # Sum of step costs entering cells
    nodes_expanded: int           # Number of nodes popped from frontier
    execution_time_ms: float      # Runtime in milliseconds
    visited_nodes: List[Tuple[int, int]] = field(default_factory=list) # Order of exploration

    def to_dict(self) -> Dict[str, Any]:
        """Convert result to JSON-serializable dictionary."""
        return {
            "algorithm_name": self.algorithm_name,
            "goal_reached": self.goal_reached,
            "path": [list(pt) for pt in self.path],
            "actions": self.actions,
            "path_length": self.path_length,
            "total_cost": self.total_cost,
            "nodes_expanded": self.nodes_expanded,
            "execution_time_ms": round(self.execution_time_ms, 3),
            "visited_nodes": [list(pt) for pt in self.visited_nodes],
        }


