def manhattan_distance(p1: Tuple[int, int], p2: Tuple[int, int]) -> float:
    """
    Computes L1 Manhattan Distance between two grid coordinates:
      h(n) = |r1 - r2| + |c1 - c2|

    MATHEMATICAL PROOF OF ADMISSIBILITY & CONSISTENCY:
    --------------------------------------------------
    1. Admissibility (Never overestimates the true remaining cost h*(n)):
       - The robot moves exclusively along cardinal axes (UP, DOWN, LEFT, RIGHT).
       - In an obstacle-free grid where all cells have the minimum traversal cost
         c_min = 1.0 (open aisles), the absolute minimum number of steps between
         (r, c) and (r_goal, c_goal) is |r - r_goal| + |c - c_goal|.
       - Crowded cells strictly increase traversal cost (cost = 4.0), and shelves/
         restricted zones force detours (increasing distance).
       - Therefore:
           h*(n) >= c_min * (|dr| + |dc|) = 1.0 * h(n) = h(n)
         Since h(n) <= h*(n) for all nodes n, Manhattan distance is strictly ADMISSIBLE.

    2. Consistency / Monotonicity (Triangle Inequality):
       - For any node n and any successor n' generated by action a:
           |h(n) - h(n')| <= 1.0
       - Since entering any cell costs at least c(n, a, n') >= 1.0:
           h(n) <= c(n, a, n') + h(n')
       - Because h(n) is consistent, A* graph search is guaranteed to find an
         optimal path without needing to reopen nodes in the closed set.
    """
    return float(abs(p1[0] - p2[0]) + abs(p1[1] - p2[1]))


