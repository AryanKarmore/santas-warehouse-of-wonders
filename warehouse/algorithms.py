def breadth_first_search(grid: WarehouseGrid) -> SearchResult:
    """
    Breadth-First Search (BFS)
    Implemented by: Atharv [BT24CSD004] (Person 2)

    Explores nodes level-by-level using a FIFO queue.
    Properties:
    - Optimal with respect to PATH LENGTH (fewest number of moves/steps).
    - Completely blind to cell traversal costs (treats crowded cells cost 4 same as cost 1).
    - Time Complexity: O(b^d), Space Complexity: O(b^d).
    """
    start_time = time.perf_counter()
    start_state = grid.start
    goal_state = grid.goal

    if grid.is_goal(start_state):
        duration = (time.perf_counter() - start_time) * 1000.0
        return SearchResult("BFS", True, [start_state], [], 0, 0.0, 1, duration, [start_state])

    # FIFO Frontier: elements are SearchNode
    frontier: deque[SearchNode] = deque([SearchNode(state=start_state, cost=0.0)])
    explored: Set[Tuple[int, int]] = {start_state}
    visited_order: List[Tuple[int, int]] = []
    nodes_expanded = 0

    while frontier:
        current_node = frontier.popleft()
        nodes_expanded += 1
        visited_order.append(current_node.state)

        for next_state, action, step_cost in grid.get_successors(current_node.state):
            if next_state not in explored:
                child_node = SearchNode(
                    state=next_state,
                    parent=current_node,
                    action=action,
                    cost=current_node.cost + step_cost
                )

                if grid.is_goal(next_state):
                    nodes_expanded += 1
                    visited_order.append(next_state)
                    path = child_node.get_path()
                    actions = child_node.get_actions()
                    duration = (time.perf_counter() - start_time) * 1000.0
                    return SearchResult(
                        algorithm_name="BFS",
                        goal_reached=True,
                        path=path,
                        actions=actions,
                        path_length=len(path) - 1,
                        total_cost=child_node.cost,
                        nodes_expanded=nodes_expanded,
                        execution_time_ms=duration,
                        visited_nodes=visited_order
                    )

                explored.add(next_state)
                frontier.append(child_node)

    duration = (time.perf_counter() - start_time) * 1000.0
    return SearchResult("BFS", False, [], [], 0, 0.0, nodes_expanded, duration, visited_order)


def depth_first_search(grid: WarehouseGrid) -> SearchResult:
    """
    Depth-First Search (DFS)
    Implemented by: Atharv [BT24CSD004] (Person 2)

    Explores deepest nodes first using a LIFO stack.
    Properties:
    - Neither optimal in path length nor optimal in path cost.
    - Graph search with visited set prevents infinite loops.
    - Demonstrates erratic, meandering exploratory paths.
    - Time Complexity: O(b^m), Space Complexity: O(b*m).
    """
    start_time = time.perf_counter()
    start_state = grid.start

    if grid.is_goal(start_state):
        duration = (time.perf_counter() - start_time) * 1000.0
        return SearchResult("DFS", True, [start_state], [], 0, 0.0, 1, duration, [start_state])

    # LIFO Frontier: elements are SearchNode
    frontier: List[SearchNode] = [SearchNode(state=start_state, cost=0.0)]
    explored: Set[Tuple[int, int]] = set()
    visited_order: List[Tuple[int, int]] = []
    nodes_expanded = 0

    while frontier:
        current_node = frontier.pop()
        current_state = current_node.state

        if current_state in explored:
            continue

        explored.add(current_state)
        nodes_expanded += 1
        visited_order.append(current_state)

        if grid.is_goal(current_state):
            path = current_node.get_path()
            actions = current_node.get_actions()
            duration = (time.perf_counter() - start_time) * 1000.0
            return SearchResult(
                algorithm_name="DFS",
                goal_reached=True,
                path=path,
                actions=actions,
                path_length=len(path) - 1,
                total_cost=current_node.cost,
                nodes_expanded=nodes_expanded,
                execution_time_ms=duration,
                visited_nodes=visited_order
            )

        for next_state, action, step_cost in grid.get_successors(current_state):
            if next_state not in explored:
                child_node = SearchNode(
                    state=next_state,
                    parent=current_node,
                    action=action,
                    cost=current_node.cost + step_cost
                )
                frontier.append(child_node)

    duration = (time.perf_counter() - start_time) * 1000.0
    return SearchResult("DFS", False, [], [], 0, 0.0, nodes_expanded, duration, visited_order)


