def greedy_best_first_search(grid: WarehouseGrid) -> SearchResult:
    """
    Greedy Best-First Search
    Implemented by: Aditya [BT24CSD018] (Person 3)

    Evaluates nodes purely by heuristic value: f(n) = h(n) = Manhattan Distance.
    Properties:
    - Highly goal-directed; often expands very few nodes when the direct line is clear.
    - Non-optimal: Ignores accumulated step cost g(n). It eagerly enters crowded cells
      (cost = 4) because they move it geographically closer to the goal, overlooking
      cheaper bypass routes.
    - Vulnerable to false starts and dead-ends when obstacles block the direct path.
    """
    start_time = time.perf_counter()
    start_state = grid.start
    goal_state = grid.goal

    initial_h = manhattan_distance(start_state, goal_state)
    start_node = SearchNode(state=start_state, cost=0.0, heuristic=initial_h)

    # Priority queue: (heuristic, tie_breaker_counter, SearchNode)
    counter = 0
    frontier: List[Tuple[float, int, SearchNode]] = [(initial_h, counter, start_node)]
    explored: Set[Tuple[int, int]] = set()
    visited_order: List[Tuple[int, int]] = []
    nodes_expanded = 0

    while frontier:
        _, _, current_node = heapq.heappop(frontier)
        current_state = current_node.state

        if current_state in explored:
            continue

        explored.add(current_state)
        nodes_expanded += 1
        visited_order.append(current_state)

        if grid.is_goal(current_state):
            path = current_node.get_path()
            actions = current_node.get_actions()
            duration = (time.perf_counter() - start_time) * 1000.0
            return SearchResult(
                algorithm_name="Greedy Best-First",
                goal_reached=True,
                path=path,
                actions=actions,
                path_length=len(path) - 1,
                total_cost=current_node.cost,
                nodes_expanded=nodes_expanded,
                execution_time_ms=duration,
                visited_nodes=visited_order
            )

        for next_state, action, step_cost in grid.get_successors(current_state):
            if next_state not in explored:
                h_val = manhattan_distance(next_state, goal_state)
                child_node = SearchNode(
                    state=next_state,
                    parent=current_node,
                    action=action,
                    cost=current_node.cost + step_cost,
                    heuristic=h_val
                )
                counter += 1
                heapq.heappush(frontier, (h_val, counter, child_node))

    duration = (time.perf_counter() - start_time) * 1000.0
    return SearchResult("Greedy Best-First", False, [], [], 0, 0.0, nodes_expanded, duration, visited_order)


def a_star_search(grid: WarehouseGrid, start_pos: Optional[Tuple[int, int]] = None) -> SearchResult:
    """
    A* Search
    Implemented by: Raveena [BT24CSD022] (Person 4)

    Evaluates nodes by estimated total cost: f(n) = g(n) + h(n)
      - g(n): Cumulative path cost from start to n
      - h(n): Manhattan distance from n to goal
    
    Properties:
    - OPTIMAL & COMPLETE: Guaranteed to find the minimum-cost route since h(n) is
      admissible and consistent.
    - Intelligently balances path length and cell traversal costs, opting for a longer
      open route (e.g. 7 steps of cost 1 = 7) instead of a shorter crowded route
      (e.g. 5 steps of cost 4 = 20).
    - Can be launched from any arbitrary start_pos (critical for Dynamic Replanning).
    """
    start_time = time.perf_counter()
    start_state = start_pos if start_pos is not None else grid.start
    goal_state = grid.goal

    initial_h = manhattan_distance(start_state, goal_state)
    start_node = SearchNode(state=start_state, cost=0.0, heuristic=initial_h)

    # Priority queue: (f_score, tie_breaker_counter, SearchNode)
    counter = 0
    frontier: List[Tuple[float, int, SearchNode]] = [(start_node.f_score, counter, start_node)]
    # Track the lowest g-cost discovered so far for each state
    best_g: Dict[Tuple[int, int], float] = {start_state: 0.0}
    visited_order: List[Tuple[int, int]] = []
    nodes_expanded = 0

    while frontier:
        f_val, _, current_node = heapq.heappop(frontier)
        current_state = current_node.state

        # Prune if we have already expanded this state with a cheaper g-cost
        if current_node.cost > best_g.get(current_state, float('inf')):
            continue

        nodes_expanded += 1
        visited_order.append(current_state)

        if grid.is_goal(current_state):
            path = current_node.get_path()
            actions = current_node.get_actions()
            duration = (time.perf_counter() - start_time) * 1000.0
            return SearchResult(
                algorithm_name="A*",
                goal_reached=True,
                path=path,
                actions=actions,
                path_length=len(path) - 1,
                total_cost=current_node.cost,
                nodes_expanded=nodes_expanded,
                execution_time_ms=duration,
                visited_nodes=visited_order
            )

        for next_state, action, step_cost in grid.get_successors(current_state):
            new_g = current_node.cost + step_cost
            if new_g < best_g.get(next_state, float('inf')):
                best_g[next_state] = new_g
                h_val = manhattan_distance(next_state, goal_state)
                child_node = SearchNode(
                    state=next_state,
                    parent=current_node,
                    action=action,
                    cost=new_g,
                    heuristic=h_val
                )
                counter += 1
                heapq.heappush(frontier, (child_node.f_score, counter, child_node))

    duration = (time.perf_counter() - start_time) * 1000.0
    return SearchResult("A*", False, [], [], 0, 0.0, nodes_expanded, duration, visited_order)
